import itertools,json,math,resource,time
from fractions import Fraction as F
resource.setrlimit(resource.RLIMIT_AS,(256*1024*1024,256*1024*1024))
start=time.monotonic()
def mul(a,b):
 c=[0]*4
 for i,x in enumerate(a):
  for j,y in enumerate(b):c[(i+j)%4]+=x*y*(1 if i+j<4 else -1)
 return tuple(c)
def ev(a,x,p):return sum(c*pow(x,i,p) for i,c in enumerate(a))%p
def nonneg(a,b):
 # Exact sign of a+b*sqrt(2).
 if a>=0 and b>=0:return True
 if a<0 and b<=0:return False
 return a*a>=2*b*b if a>=0 else 2*b*b>=a*a
cases=[]
for p,eta,q in [(1,0,17),(17,2,17),(17,2,5),(41,3,17)]:
 if p>1:assert (eta**4+1)%p==0
 counts=0;inequalities=0;minnorm=None
 for x in itertools.product(range(-2,3),repeat=4):
  if not any(x) or (p>1 and ev(x,eta,p)!=0):continue
  a=sum(t*t for t in x);b=x[0]*x[1]+x[1]*x[2]+x[2]*x[3]-x[0]*x[3]
  norm=a*a-2*b*b
  assert norm>0 and norm%p==0
  minnorm=norm if minnorm is None else min(minnorm,norm)
  for w,W in [(1,1),(1,3),(2,17)]:
   # Weighted canonical square is (aa+bb sqrt2)/(16q²).
   aa=2*(W*W+w*w)*a;bb=2*(W*W-w*w)*b
   assert nonneg(aa,bb)
   # Squared AM-GM lower bound from N(x)>=p, no floating point.
   assert nonneg(aa*aa+2*bb*bb-16*w*w*W*W*p,2*aa*bb)
   inequalities+=1
  counts+=1
 cases.append({'ideal_norm':p,'root':eta,'q':q,'gcd':math.gcd(p,q),'chain_compatible':math.gcd(p,q)==1,'nonzero_box_members':counts,'minimum_absolute_norm':minnorm,'exact_weighted_norm_inequalities':inequalities})
shift=[]
for p,eta,q in [(17,2,17),(17,2,5),(41,3,17)]:
 a=(eta**3,eta**2,eta,1);lam=tuple(F(q*t,p) for t in a)
 e=(F(1,100),F(-1,100),F(2,100),F(0));g=(F(-1,50),F(0),F(1,50),F(0))
 T=tuple(x+y for x,y in zip(lam,e));checked=0
 for r in itertools.product((-1,0,1),repeat=4):
  left=mul(r,tuple(x-y for x,y in zip(T,g)));right=mul(r,tuple(x-y for x,y in zip(e,g)))
  diff=tuple(x-y for x,y in zip(left,right));assert diff==mul(r,lam)
  # J generated by p and X-eta; verify (diff/q)*J subset R.
  unscaled=tuple(t/q for t in diff)
  assert all((p*t).denominator==1 for t in unscaled)
  assert all(t.denominator==1 for t in mul(unscaled,(-eta,1,0,0)))
  checked+=1
 shift.append({'p':p,'q':q,'r_cases':checked,'lambda_numerators':a,'denominator':p,'includes_zero_negative_nonunits':True})
completion=0
for v in [F(2),F(3),F(10**6)]:
 for h in [F(0),F(1,100),F(-1,4),F(1,2)]:
  w=F(1);P=1/(1/v**2+h*h/w**2);C=w*w+h*h*v*v
  assert P>=2 and P*C==v*v*w*w
  for r,y in itertools.product([F(-2),F(0),F(3,2)],repeat=2):
   m=P*h*y/(w*w)
   assert r*r/(v*v)+(y-h*r)**2/(w*w)==(r-m)**2/P+y*y/C
   completion+=1
print(json.dumps({'reservation':'C-OHCP-1','method':'exhaustive exact integer/Fraction/Q(sqrt2) comparisons; no random seed','dimension':4,'coefficient_box':[-2,2],'ideal_controls':cases,'shift_controls':shift,'completion_identity_cases':completion,'tail':'finite exhaustive algebraic control; no numerical Gaussian truncation or unproved tail estimate','assertions':'passed','resources':{'elapsed_seconds':time.monotonic()-start,'maxrss_kib':resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,'address_space_limit_bytes':256*1024*1024}},indent=2))
